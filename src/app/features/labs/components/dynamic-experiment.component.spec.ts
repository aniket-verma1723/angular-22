import { NgComponentOutlet } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { By } from '@angular/platform-browser';
import { labButton, labElement } from './component-lab.spec-helpers';
import { DynamicExperimentComponent } from './dynamic-experiment.component';
import { LAB_WIDGETS } from './dynamic-widgets.component';
import type { WidgetContract, WidgetKind, WidgetSelection } from './dynamic-widgets.component';
import { WidgetLifetime } from './widget-lifetime.service';

describe('DynamicExperimentComponent', () => {
  beforeEach(() => TestBed.configureTestingModule({ imports: [DynamicExperimentComponent], providers: [WidgetLifetime] }));

  it('renders both allowlisted widget input contracts as text and reports the latest revision once', async () => {
    const kinds: readonly WidgetKind[] = ['note', 'meter'];
    for (const kind of kinds) {
      const fixture = TestBed.createComponent<WidgetContract>(LAB_WIDGETS[kind]);
      const selections: WidgetSelection[] = [];
      const title = '<img src=x onerror=alert(1)>';
      fixture.componentRef.setInput('data', { title, revision: 0 });
      fixture.componentRef.setInput('onSelection', (value: WidgetSelection) => selections.push(value));
      fixture.autoDetectChanges();
      await fixture.whenStable();
      const root: HTMLElement = fixture.nativeElement;
      expect(root.querySelector('[data-widget]')?.textContent).toContain(title);
      expect(root.querySelector('img')).toBeNull();
      fixture.componentRef.setInput('data', { title, revision: 2 });
      await fixture.whenStable();
      labButton(root, `Select ${kind} revision`).click();
      await fixture.whenStable();
      expect(selections).toEqual([{ kind, revision: 2 }]);
      fixture.destroy();
    }
  });

  it('starts empty and binds typed inputs and outputs without recreating the live widget', async () => {
    const fixture = TestBed.createComponent(DynamicExperimentComponent);
    fixture.autoDetectChanges();
    await fixture.whenStable();
    const root: HTMLElement = fixture.nativeElement;
    expect(root.querySelector('[data-created]')?.textContent).toBe('0');
    expect(root.querySelector('[data-widget]')).toBeNull();
    expect(Object.keys(LAB_WIDGETS)).toEqual(['note', 'meter']);
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    const widget = labElement(root, 'app-note-widget');
    expect(widget.textContent).toContain('Trusted local fixture · revision 0');
    labButton(root, 'Update widget input').click();
    await fixture.whenStable();
    expect(labElement(root, 'app-note-widget')).toBe(widget);
    expect(widget.textContent).toContain('revision 1');
    labButton(root, 'Read widget lifetime').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-created]')?.textContent).toBe('1');
    labButton(root, 'Select note revision').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('Selected note revision 1');
  });

  it('destroys replaced and cleared views, removes old listeners, and cleans up on owner destruction', async () => {
    const fixture = TestBed.createComponent(DynamicExperimentComponent);
    fixture.autoDetectChanges();
    await fixture.whenStable();
    const root: HTMLElement = fixture.nativeElement;
    const lifetime = fixture.debugElement.injector.get(WidgetLifetime);
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    const oldButton = labButton(root, 'Select note revision');
    labButton(root, 'Create meter').click();
    await fixture.whenStable();
    expect(lifetime.snapshot()).toEqual({ created: 2, destroyed: 1 });
    expect(root.querySelector('app-note-widget')).toBeNull();
    oldButton.click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('No selection yet');
    labButton(root, 'Select meter revision').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('Selected meter revision 0');
    const oldMeter = labElement(root, 'app-meter-widget');
    labButton(root, 'Create meter').click();
    await fixture.whenStable();
    expect(labElement(root, 'app-meter-widget')).not.toBe(oldMeter);
    expect(lifetime.snapshot()).toEqual({ created: 3, destroyed: 2 });
    labButton(root, 'Clear widget').click();
    await fixture.whenStable();
    expect(lifetime.snapshot()).toEqual({ created: 3, destroyed: 3 });
    expect(root.querySelector('[data-widget]')).toBeNull();
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    fixture.destroy();
    expect(lifetime.snapshot()).toEqual({ created: 4, destroyed: 4 });
  });

  it('uses the real outlet with typed input updates and explicit selection, destroying same-kind replacements and switched views', async () => {
    const fixture = TestBed.createComponent(DynamicExperimentComponent);
    fixture.autoDetectChanges();
    await fixture.whenStable();
    const root: HTMLElement = fixture.nativeElement;
    const lifetime = fixture.debugElement.injector.get(WidgetLifetime);
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    const containerButton = labButton(root, 'Select note revision');
    labButton(root, 'Switch widget implementation').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-implementation]')?.textContent).toContain('NgComponentOutlet');
    expect(root.querySelector('[data-widget]')).toBeNull();
    expect(lifetime.snapshot()).toEqual({ created: 1, destroyed: 1 });
    containerButton.click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('No selection yet');
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    const note = labElement(root, 'app-note-widget');
    expect(fixture.debugElement.queryAllNodes(By.directive(NgComponentOutlet))).toHaveSize(1);
    labButton(root, 'Update widget input').click();
    await fixture.whenStable();
    expect(labElement(root, 'app-note-widget')).toBe(note);
    expect(note.textContent).toContain('Trusted local fixture · revision 1');
    labButton(root, 'Select note revision').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('Selected note revision 1');
    const oldButton = labButton(root, 'Select note revision');
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    expect(labElement(root, 'app-note-widget')).not.toBe(note);
    expect(lifetime.snapshot()).toEqual({ created: 3, destroyed: 2 });
    oldButton.click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('No selection yet');
    labButton(root, 'Create meter').click();
    await fixture.whenStable();
    expect(root.querySelectorAll('[data-widget]').length).toBe(1);
    expect(root.querySelector('app-note-widget')).toBeNull();
    labButton(root, 'Select meter revision').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-selection]')?.textContent).toContain('Selected meter revision 1');
    labButton(root, 'Read widget lifetime').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-created]')?.textContent).toBe('4');
    expect(root.querySelector('[data-destroyed]')?.textContent).toBe('3');
    labButton(root, 'Clear widget').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-widget]')).toBeNull();
    expect(lifetime.snapshot()).toEqual({ created: 4, destroyed: 4 });
    labButton(root, 'Create meter').click();
    await fixture.whenStable();
    labButton(root, 'Switch widget implementation').click();
    await fixture.whenStable();
    expect(root.querySelector('[data-implementation]')?.textContent).toContain('ViewContainerRef.createComponent');
    expect(lifetime.snapshot()).toEqual({ created: 5, destroyed: 5 });
    labButton(root, 'Switch widget implementation').click();
    labButton(root, 'Create note').click();
    await fixture.whenStable();
    fixture.destroy();
    expect(lifetime.snapshot()).toEqual({ created: 6, destroyed: 6 });
  });
});
